/// Every entry: [`TABLE`] and the tables of the submodules (split for the
/// line budget; add new entries to the last one).
pub fn entries() -> impl Iterator<Item = &'static (&'static str, &'static str)> {
    TABLE
        .iter()
        .chain(operations::TABLE)
        .chain(flat_links::TABLE)
        .chain(tabs::TABLE)
        .chain(views::TABLE)
        .chain(zoom_select::TABLE)
        .chain(cloud::TABLE)
        .chain(libraries::TABLE)
        .chain(help_views::TABLE)
        .chain(search_tags::TABLE)
        .chain(search_history::TABLE)
        .chain(cleanup::TABLE)
        .chain(disk_usage::TABLE)
        .chain(help_search::TABLE)
        .chain(index_live::TABLE)
        .chain(picture_tools::TABLE)
        .chain(pictures::TABLE)
        .chain(player_more::TABLE)
        .chain(preview_docs::TABLE)
        .chain(data_view::TABLE)
        .chain(help_preview::TABLE)
        .chain(wsl::TABLE)
        .chain(commands::TABLE)
        .chain(git_ops::TABLE)
        .chain(remote::TABLE)
        .chain(remote_more::TABLE)
        .chain(help_more::TABLE)
        .chain(help_tools::TABLE)
        .chain(mirror_undo::TABLE)
        .chain(views_more::TABLE)
        .chain(previews_more::TABLE)
        .chain(notify_keys_stash::TABLE)
        .chain(fulltext::TABLE)
        .chain(index_service::TABLE)
}
